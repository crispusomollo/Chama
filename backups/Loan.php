<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class Loan extends Model
{
    protected $fillable = [

        /*
        |--------------------------------------------------------------------------
        | RELATIONSHIPS
        |--------------------------------------------------------------------------
        */

        'borrower_id',

        /*
        |--------------------------------------------------------------------------
        | LOAN DETAILS
        |--------------------------------------------------------------------------
        */

        'amount',
        'principal_amount',
        'interest_rate',
        'interest_amount',

        'duration_months',

        'loan_date',
        'due_date',
        'disbursement_date',

        /*
        |--------------------------------------------------------------------------
        | FINANCIALS
        |--------------------------------------------------------------------------
        */

        'total_payable',
        'monthly_installment',
        'balance',

        /*
        |--------------------------------------------------------------------------
        | CREDIT ENGINE
        |--------------------------------------------------------------------------
        */

        'credit_score',
        'system_recommendation',

        /*
        |--------------------------------------------------------------------------
        | STATUSES
        |--------------------------------------------------------------------------
        */

        'application_status',
        'loan_status',
    ];

    /*
    |--------------------------------------------------------------------------
    | RELATIONSHIPS
    |--------------------------------------------------------------------------
    */

    public function borrower()
    {
        return $this->belongsTo(Borrower::class);
    }

    public function repayments()
    {
        return $this->hasMany(Repayment::class);
    }

    /*
    |--------------------------------------------------------------------------
    | TOTAL REPAID
    |--------------------------------------------------------------------------
    */

    public function totalRepaid()
    {
        return $this->repayments()->sum('amount');
    }

    /*
    |--------------------------------------------------------------------------
    | OUTSTANDING BALANCE
    |--------------------------------------------------------------------------
    */

    public function outstandingBalance()
    {
        return $this->balance;
    }

    /*
    |--------------------------------------------------------------------------
    | RECONCILIATION ENGINE
    |--------------------------------------------------------------------------
    */

    public function recalculateLoan()
    {
        $paid = $this->totalRepaid();

        /*
        |--------------------------------------------------------------------------
        | UPDATE BALANCE
        |--------------------------------------------------------------------------
        */

        $this->balance = $this->total_payable - $paid;

        if ($this->balance < 0) {

            $this->balance = 0;
        }

        /*
        |--------------------------------------------------------------------------
        | DETERMINE LOAN STATUS
        |--------------------------------------------------------------------------
        */

        /*
        |--------------------------------------------------------------------------
        | FULLY PAID
        |--------------------------------------------------------------------------
        */

        if ($this->balance <= 0) {

            $this->loan_status = 'completed';
        }

        /*
        |--------------------------------------------------------------------------
        | PARTIALLY PAID
        |--------------------------------------------------------------------------
        */

        elseif ($paid > 0) {

            $this->loan_status = 'ongoing';
        }

        /*
        |--------------------------------------------------------------------------
        | OVERDUE
        |--------------------------------------------------------------------------
        */

        if (
            $this->due_date &&
            now()->greaterThan($this->due_date) &&
            $this->balance > 0
        ) {

            $this->loan_status = 'overdue';
        }

        $this->save();
    }

    /*
    |--------------------------------------------------------------------------
    | CHECK IF REPAYMENT IS ALLOWED
    |--------------------------------------------------------------------------
    */

    public function canRepay()
    {
        return in_array($this->loan_status, [

            'active',
            'ongoing',
            'overdue',

        ]);
    }

    /*
    |--------------------------------------------------------------------------
    | CHECK IF LOAN IS COMPLETED
    |--------------------------------------------------------------------------
    */

    public function isCompleted()
    {
        return $this->loan_status === 'completed';
    }

    /*
    |--------------------------------------------------------------------------
    | CHECK IF LOAN IS ACTIVE
    |--------------------------------------------------------------------------
    */

    public function isActive()
    {
        return in_array($this->loan_status, [

            'active',
            'ongoing',
            'overdue',

        ]);
    }
}